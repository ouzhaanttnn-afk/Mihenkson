import type { ConditionGrade, ItemFamily, Karat, MetalKind } from '@domain/types';
import { MARKET_BASE } from '@domain/balance';
import { INVESTMENT_BANGLE_WEIGHTS, investmentBangleTemplateId } from './bullion';

export interface ItemTemplate {
  id: string;
  displayName: string;
  family: ItemFamily;
  metal: MetalKind;
  /** Nominal ayar. Gerçek ayar spawn'da sapabilir (yanlış beyan vakası). */
  nominalKarat: Karat;
  /** Brüt ağırlık bandı (gram). */
  weightBand: [number, number];
  /** Net metal ağırlığının brüte oranı bandı (taş/aksesuar payı). */
  netRatioBand: [number, number];
  /** İşçilik değerinin metal değerine oranı bandı. */
  craftsmanshipRatioBand: [number, number];
  /** Kondisyon dağılımı ağırlıkları. */
  conditionWeights: Partial<Record<ConditionGrade, number>>;
  /** Taş taşıyabilir mi. */
  hasStone: boolean;
  /** 0–1 nadirlik bandı. */
  rarityBand: [number, number];
  /** Gizli kusur çıkma olasılığı. */
  flawChance: number;
  demandTags: string[];
  /** Bu şablon hangi mağaza kademesinden itibaren müşteri havuzuna girer. */
  minTier: number;
  /** Tasarım notu — şablonun oyun içindeki öğretici rolü. */
  designNote: string;
  /** Ürün silüeti — kod ile çizilen placeholder görsel (GDD EK H "kodla çizilir"). */
  silhouette: 'bar' | 'coin' | 'chain' | 'ring' | 'bracelet' | 'necklace' | 'earring' | 'object' | 'brooch';
}

